export function sanitizeCanonicalMemory(
  candidate: unknown,
  existing: string[],
  maxMemory = 30
) {
  if (!Array.isArray(candidate)) {
    return existing.slice(-maxMemory);
  }

  const cleaned = candidate
    .filter(
      (item): item is string =>
        typeof item === "string"
    )
    .map((item) => item.trim())
    .filter(Boolean)
    .filter((item) => item.length <= 500);

  if (cleaned.length === 0 && existing.length > 0) {
    // モデルの出力事故で既存記憶が全消去されるのを防ぐ。
    return existing.slice(-maxMemory);
  }

  return Array.from(new Set(cleaned))
    .slice(-maxMemory);
}
